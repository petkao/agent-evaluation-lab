
def evaluate_tool_call(expected, actual):
    # Check whether the agent selected the correct tool
    tool_correct = expected["tool"] == actual["tool"]

    # Compare each expected argument
    expected_args = expected["arguments"]
    actual_args = actual["arguments"]

    argument_results = {}

    for key, expected_value in expected_args.items():
        actual_value = actual_args.get(key)

        argument_results[key] = (
            expected_value == actual_value
        )

    # Calculate argument accuracy
    correct_count = sum(argument_results.values())
    total_count = len(argument_results)

    argument_accuracy = (
        correct_count / total_count
        if total_count > 0
        else 1.0
    )

    # Overall correctness
    all_correct = (
        tool_correct
        and all(argument_results.values())
    )

    return {
        "tool_correct": tool_correct,
        "argument_results": argument_results,
        "argument_accuracy": argument_accuracy,
        "all_correct": all_correct
    }


# Expected tool call
expected = {
    "tool": "search_hotels",
    "arguments": {
        "city": "Tokyo",
        "max_price": 200
    }
}

# Actual tool call generated by the agent
# (Simulated for this exercise)
actual = {
    "tool": "search_hotels",
    "arguments": {
        "city": "Tokyo",
        "max_price": 500
    }
}

result = evaluate_tool_call(expected, actual)

print("\nTool Call Evaluation")
print("--------------------")
print("Expected:", expected)
print("Actual:", actual)
print("Evaluation:", result)

